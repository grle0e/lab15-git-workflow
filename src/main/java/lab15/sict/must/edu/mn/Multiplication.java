package lab15.sict.must.edu.mn;

/**
 * Үржүүлэх боломж агуулсан класс.
 */
public class Multiplication {
    /**
     * Хоёр тоог үржүүлнэ.
     *
     * @param a эхний тоо
     * @param b хоёр дахь тоо
     * @return a ба b-ийн үржвэр
     */
    public double multiply(double a, double b) {
        return a * b;
    }
}